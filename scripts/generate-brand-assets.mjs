/** Keep vector consumers in sync with the supplied EasyWork brand originals. */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(import.meta.dirname, '..')
export const BRAND_DIRECTORY = resolve(root, 'assets/brand')

export async function readBrandPalette() {
  const source = await readFile(resolve(BRAND_DIRECTORY, 'EasyWork-colors.txt'), 'utf8')
  const colors = Object.fromEntries([...source.matchAll(/^(Teal|Charcoal|White): (#[0-9A-F]{6})\s*$/gmu)].map(match => [match[1], match[2]]))
  for (const name of ['Teal', 'Charcoal', 'White']) {
    if (!colors[name]) throw new Error(`EasyWork palette is missing ${name}`)
  }
  return colors
}

export async function generateBrandAssets({ check = false } = {}) {
  const [symbolSource, logoSource, colors] = await Promise.all([
    readFile(resolve(BRAND_DIRECTORY, 'EasyWork-symbol.svg'), 'utf8'),
    readFile(resolve(BRAND_DIRECTORY, 'EasyWork-logo.svg'), 'utf8'),
    readBrandPalette(),
  ])
  const symbol = symbolSource.replaceAll('\r\n', '\n')
  const logo = logoSource.replaceAll('\r\n', '\n')
  const viewBox = /viewBox="([^"]+)"/u.exec(symbol)?.[1]
  const paths = [...symbol.matchAll(/<path\b([^>]+)\/>/gu)]
  const attribute = name => new RegExp(`\\b${name}="([^"]+)"`, 'u').exec(paths[0]?.[1] ?? '')?.[1]
  const d = attribute('d')
  const transform = attribute('transform')
  if (!viewBox || paths.length !== 1 || !d || !transform || attribute('fill') !== colors.Teal) {
    throw new Error('EasyWork symbol must contain one self-contained path in the canonical teal')
  }
  const component = `// Generated by scripts/generate-brand-assets.mjs from assets/brand/EasyWork-symbol.svg.
import * as React from 'react';

export type LogoMarkProps = {
  readonly size?: number;
  readonly title?: string;
};

export function LogoMark({ size = 24, title }: LogoMarkProps) {
  const labelled = Boolean(title);
  return (
    <svg width={size} height={size} viewBox="${viewBox}" role={labelled ? 'img' : undefined} aria-label={title} aria-hidden={labelled ? undefined : true} focusable={false}>
      <path d="${d}" fill="${colors.Teal}" transform="${transform}" />
    </svg>
  );
}
`
  const outputs = new Map([
    ['packages/ui/src/components/LogoMark.tsx', component],
    ['apps/desktop/build/tray-icon.svg', symbol],
    ['apps/web/assets/brand/workdsh-mark.svg', symbol],
    ['apps/web/assets/brand/workdsh-logo.svg', logo],
  ])
  for (const [path, content] of outputs) {
    const output = resolve(root, path)
    const actual = await readFile(output, 'utf8').catch(error => {
      if (error.code === 'ENOENT') return undefined
      throw error
    })
    if (actual === content) continue
    if (check) throw new Error(`Brand asset is stale: ${path}; run node scripts/generate-brand-assets.mjs`)
    await writeFile(output, content)
  }
  console.log(`EasyWork vector assets ${check ? 'verified' : 'generated'}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateBrandAssets({ check: process.argv.includes('--check') })
}
